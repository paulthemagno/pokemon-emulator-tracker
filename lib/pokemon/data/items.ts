export function getGen1ItemName(id: number): string {
  const machineName = getGen1MachineItemName(id);
  if (machineName) return machineName;
  return GEN1_ITEMS[id] || `Unknown (${id})`;
}

export function getGen2ItemName(id: number): string {
  return GEN2_ITEMS[id] || `Unknown (${id})`;
}

export function getGen3ItemById(id: number): ItemData | undefined {
  return GEN3_ITEMS.find(item => item.id === id);
}

export function getGen3ItemName(id: number): string {
  const item = getGen3ItemById(id);
  return item?.name || `Unknown (${id})`;
}
