// Emerald Frontier Pass symbols, using the original indexed pixels and palettes.
import fs from 'node:fs/promises';
import path from 'node:path';
import { inflateSync } from 'node:zlib';
import { execFileSync } from 'node:child_process';
const commit = '0d3100185e0b13faabfc589fc402dd46f83c1d6a';
const root = process.argv[2] ?? `.cache/pokemon-source/pokeemerald-${commit}`;
if (execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim() !== commit) throw new Error('Unexpected PRET commit');
const source = path.join(root, 'graphics/frontier_pass');
const png = await fs.readFile(path.join(source, 'medals.png'));
let width, height;
const chunks = [];
for (let offset = 8; offset < png.length;) {
  const length = png.readUInt32BE(offset), type = png.toString('ascii', offset + 4, offset + 8);
  const bytes = png.subarray(offset + 8, offset + 8 + length);
  if (type === 'IHDR') {
    width = bytes.readUInt32BE(0); height = bytes.readUInt32BE(4);
    if (width !== 16 || height !== 112 || bytes[8] !== 4 || bytes[9] !== 3 || bytes[12] !== 0) throw new Error('Unexpected indexed symbol sheet');
  }
  if (type === 'IDAT') chunks.push(bytes);
  offset += length + 12;
}
const raw = inflateSync(Buffer.concat(chunks));
const rows = [];
for (let y = 0; y < height; y++) {
  const filter = raw[y * 9], row = Buffer.from(raw.subarray(y * 9 + 1, y * 9 + 9));
  for (let x = 0; x < 8; x++) {
    const left = row[x - 1] ?? 0, up = rows[y - 1]?.[x] ?? 0, corner = rows[y - 1]?.[x - 1] ?? 0;
    const p = left + up - corner;
    const pa = Math.abs(p - left), pb = Math.abs(p - up), pc = Math.abs(p - corner);
    const predictor = filter === 0 ? 0 : filter === 1 ? left : filter === 2 ? up : filter === 3 ? Math.floor((left + up) / 2) : filter === 4 ? (pa <= pb && pa <= pc ? left : pb <= pc ? up : corner) : NaN;
    if (!Number.isFinite(predictor)) throw new Error('Unexpected PNG filter');
    row[x] = (row[x] + predictor) & 255;
  }
  rows.push(row);
}
// src/frontier_pass.c sAnims_Medal: seven 16x16 frames in facility order.
const facilities = ['tower','dome','palace','arena','factory','pike','pyramid'];
await fs.mkdir('public/frontier', {recursive:true});
for (const tier of ['silver','gold']) {
  const palette = (await fs.readFile(path.join(source, `${tier}.pal`), 'utf8')).trim().split(/\r?\n/).slice(3).map(line => '#' + line.trim().split(/\s+/).map(n => Number(n).toString(16).padStart(2,'0')).join(''));
  if (palette.length !== 16) throw new Error('Unexpected palette size');
  for (let frame = 0; frame < 7; frame++) {
    const rects = [];
    for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
      const index = (rows[frame * 16 + y][x >> 1] >> (x % 2 ? 0 : 4)) & 15;
      if (index) rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${palette[index]}"/>`);
    }
    await fs.writeFile(`public/frontier/${facilities[frame]}-${tier}.svg`, `<!-- Generated by scripts/generate-frontier-symbols.mjs from pret/pokeemerald ${commit}: graphics/frontier_pass/medals.png + ${tier}.pal. Palette index 0 is transparent. -->\n<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" shape-rendering="crispEdges">\n${rects.join('\n')}\n</svg>\n`);
  }
}
console.log('Generated 14 Frontier Pass symbols.');
