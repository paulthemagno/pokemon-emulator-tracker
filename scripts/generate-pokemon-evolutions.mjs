import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const outputPath = path.join(root, "lib/pokemon/data/pokemon-evolutions.ts");
const maxSpeciesId = 386;
const concurrency = 6;

function normalizeName(name) {
  return String(name ?? "")
    .split("-")
    .map((part) => part ? `${part[0].toUpperCase()}${part.slice(1)}` : part)
    .join(" ");
}

async function fetchJson(url) {
  const response = await fetch(url, {
    headers: {
      "User-Agent": "pokemon-emulator-tracker knowledge generator",
    },
  });
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`);
  }
  return response.json();
}

async function mapLimit(items, limit, worker) {
  const results = [];
  let nextIndex = 0;

  async function run() {
    while (nextIndex < items.length) {
      const index = nextIndex++;
      results[index] = await worker(items[index], index);
    }
  }

  await Promise.all(Array.from({ length: limit }, run));
  return results;
}

function getResourceId(url) {
  const match = String(url ?? "").match(/\/(\d+)\/?$/);
  return match ? Number(match[1]) : undefined;
}

function compactDetail(detail) {
  const trigger = detail.trigger?.name;
  const item = detail.item?.name;
  const heldItem = detail.held_item?.name;
  const knownMove = detail.known_move?.name;
  const knownMoveType = detail.known_move_type?.name;
  const location = detail.location?.name;

  return {
    trigger,
    minLevel: detail.min_level ?? undefined,
    minHappiness: detail.min_happiness ?? undefined,
    minBeauty: detail.min_beauty ?? undefined,
    minAffection: detail.min_affection ?? undefined,
    item,
    heldItem,
    timeOfDay: detail.time_of_day || undefined,
    knownMove,
    knownMoveType,
    location,
    gender: detail.gender ?? undefined,
    needsOverworldRain: detail.needs_overworld_rain || undefined,
    turnUpsideDown: detail.turn_upside_down || undefined,
    relativePhysicalStats: detail.relative_physical_stats ?? undefined,
    tradeSpecies: detail.trade_species?.name,
  };
}

function flattenChain(node, speciesByName, edges) {
  const from = speciesByName.get(node.species?.name);
  if (!from || from.id > maxSpeciesId) return;

  for (const child of node.evolves_to ?? []) {
    const to = speciesByName.get(child.species?.name);
    if (to && to.id <= maxSpeciesId) {
      const details = (child.evolution_details ?? []).map(compactDetail);
      edges.push({
        fromId: from.id,
        from: from.name,
        toId: to.id,
        to: to.name,
        details: details.length > 0 ? details : [{ trigger: "unknown" }],
      });
    }
    flattenChain(child, speciesByName, edges);
  }
}

const speciesIds = Array.from({ length: maxSpeciesId }, (_, index) => index + 1);
const speciesRows = await mapLimit(speciesIds, concurrency, async (id, index) => {
  if ((index + 1) % 25 === 0) {
    console.log(`Fetched species ${index + 1}/${maxSpeciesId}`);
  }
  const data = await fetchJson(`https://pokeapi.co/api/v2/pokemon-species/${id}`);
  return {
    id,
    slug: data.name,
    name: normalizeName(data.name),
    chainId: getResourceId(data.evolution_chain?.url),
  };
});

const speciesByName = new Map(speciesRows.map((entry) => [entry.slug, entry]));
const chainIds = [...new Set(speciesRows.map((entry) => entry.chainId).filter(Boolean))].sort(
  (a, b) => a - b
);

const chains = await mapLimit(chainIds, concurrency, async (chainId, index) => {
  if ((index + 1) % 25 === 0) {
    console.log(`Fetched evolution chains ${index + 1}/${chainIds.length}`);
  }
  return fetchJson(`https://pokeapi.co/api/v2/evolution-chain/${chainId}`);
});

const edges = [];
for (const chain of chains) {
  flattenChain(chain.chain, speciesByName, edges);
}
edges.sort((a, b) => a.fromId - b.fromId || a.toId - b.toId);

const body = `// Generated by scripts/generate-pokemon-evolutions.mjs.
// Source: PokeAPI pokemon-species and evolution-chain resources for National Dex 1-386.
// Do not edit this file by hand; rerun the generator.

export interface PokemonEvolutionDetail {
  trigger?: string;
  minLevel?: number;
  minHappiness?: number;
  minBeauty?: number;
  minAffection?: number;
  item?: string;
  heldItem?: string;
  timeOfDay?: string;
  knownMove?: string;
  knownMoveType?: string;
  location?: string;
  gender?: number;
  needsOverworldRain?: boolean;
  turnUpsideDown?: boolean;
  relativePhysicalStats?: number;
  tradeSpecies?: string;
}

export interface PokemonEvolutionEdge {
  fromId: number;
  from: string;
  toId: number;
  to: string;
  details: PokemonEvolutionDetail[];
}

export const POKEMON_EVOLUTIONS: PokemonEvolutionEdge[] = ${JSON.stringify(edges, null, 2)};
`;

await fs.writeFile(outputPath, body);
console.log(`Wrote ${edges.length} evolution edges to ${outputPath}`);
