import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const outputPath = path.join(root, "lib/pokemon/data/pokemon-learnsets.ts");
const maxSpeciesId = 386;
const maxMoveId = 354;
const concurrency = 6;
const supportedVersionGroups = new Set([
  "red-blue",
  "yellow",
  "gold-silver",
  "crystal",
  "ruby-sapphire",
  "emerald",
  "firered-leafgreen",
]);

async function fetchJson(url) {
  const response = await fetch(url, {
    headers: {
      "User-Agent": "pokemon-emulator-tracker knowledge generator",
    },
  });
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`);
  }
  return response.json();
}

async function mapLimit(items, limit, worker) {
  const results = [];
  let nextIndex = 0;

  async function run() {
    while (nextIndex < items.length) {
      const index = nextIndex++;
      results[index] = await worker(items[index], index);
    }
  }

  await Promise.all(Array.from({ length: limit }, run));
  return results;
}

function getResourceId(url) {
  const match = String(url ?? "").match(/\/(\d+)\/?$/);
  return match ? Number(match[1]) : undefined;
}

const speciesIds = Array.from({ length: maxSpeciesId }, (_, index) => index + 1);
const rows = [];

await mapLimit(speciesIds, concurrency, async (speciesId, index) => {
  if ((index + 1) % 25 === 0) {
    console.log(`Fetched learnsets ${index + 1}/${speciesIds.length}`);
  }
  const data = await fetchJson(`https://pokeapi.co/api/v2/pokemon/${speciesId}`);
  for (const moveEntry of data.moves ?? []) {
    const moveId = getResourceId(moveEntry.move?.url);
    if (!moveId || moveId > maxMoveId) continue;
    for (const detail of moveEntry.version_group_details ?? []) {
      const versionGroup = detail.version_group?.name;
      if (!supportedVersionGroups.has(versionGroup)) continue;
      rows.push({
        speciesId,
        moveId,
        versionGroup,
        method: detail.move_learn_method?.name ?? "unknown",
        level: detail.level_learned_at ?? 0,
      });
    }
  }
});

rows.sort(
  (left, right) =>
    left.speciesId - right.speciesId ||
    left.versionGroup.localeCompare(right.versionGroup) ||
    left.level - right.level ||
    left.method.localeCompare(right.method) ||
    left.moveId - right.moveId
);

const body = `// Generated by scripts/generate-pokemon-learnsets.mjs.
// Source: PokeAPI pokemon move version-group details for National Dex 1-386 and Gen 1-3 moves.
// Do not edit this file by hand; rerun the generator.

export type PokemonLearnsetEntry = readonly [
  speciesId: number,
  moveId: number,
  versionGroup: string,
  method: string,
  level: number,
];

export const POKEMON_LEARNSETS: readonly PokemonLearnsetEntry[] = ${JSON.stringify(
  rows.map((row) => [
    row.speciesId,
    row.moveId,
    row.versionGroup,
    row.method,
    row.level,
  ])
)};
`;

await fs.writeFile(outputPath, body);
console.log(`Wrote ${rows.length} learnset rows to ${outputPath}`);
