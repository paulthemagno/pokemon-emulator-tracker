import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourceDir = path.join(root, "lib/pokemon/knowledge/sources");
const cacheDir = path.join(root, ".cache/pokemon-source");
const candidatesPath = path.join(sourceDir, "progress-fact-candidates.json");
const provenancePath = path.join(sourceDir, "provenance.json");
const outputPath = path.join(root, "docs/progress-facts-prototype.md");

const repoFolderBySource = {
  pretPokered: "pokered",
  pretPokeyellow: "pokeyellow",
  pretPokegold: "pokegold",
  pokecrystal: "pokecrystal",
  pretPokeruby: "pokeruby",
  pretPokeemerald: "pokeemerald",
  pretPokefirered: "pokefirered",
};

async function readJson(filePath) {
  return JSON.parse(await fs.readFile(filePath, "utf8"));
}

function sourceUrl(source, filePath, line) {
  return `https://github.com/${source.repo}/blob/${source.commit}/${filePath}#L${line}`;
}

function findPatternLine(text, pattern) {
  const lines = text.split(/\r?\n/);
  const index = lines.findIndex((line) => line.includes(pattern));
  return index === -1 ? undefined : index + 1;
}

async function loadEvidence(candidate, evidence, provenance) {
  const source = provenance[evidence.sourceKey];
  const repoFolder = repoFolderBySource[evidence.sourceKey];
  if (!source?.repo || !source.commit || !repoFolder) {
    throw new Error(`${candidate.id}: incomplete provenance for ${evidence.sourceKey}`);
  }

  const repoPath = path.join(cacheDir, `${repoFolder}-${source.commit}`);
  const fullPath = path.join(repoPath, evidence.path);
  let text;
  try {
    text = await fs.readFile(fullPath, "utf8");
  } catch {
    throw new Error(
      `${candidate.id}: missing pinned checkout file ${fullPath}. Run an existing --from-github extractor first.`
    );
  }

  const matches = evidence.patterns.map((pattern) => {
    const line = findPatternLine(text, pattern);
    if (!line) {
      throw new Error(`${candidate.id}: pattern "${pattern}" not found in ${evidence.path}`);
    }
    return {
      pattern,
      line,
      url: sourceUrl(source, evidence.path, line),
    };
  });

  return {
    sourceName: source.name,
    path: evidence.path,
    matches,
  };
}

function renderCandidate(candidate, evidence) {
  const games = candidate.games.map((game) => `\`${game}\``).join(", ");
  const sources = evidence
    .flatMap((item) =>
      item.matches.map(
        (match) => `- [${item.sourceName}: ${item.path} line ${match.line}](${match.url}) verifies \`${match.pattern}\`.`
      )
    )
    .join("\n");

  return `### ${candidate.title}

- **Games:** ${games}
- **Type:** \`${candidate.kind}\`
- **Priority:** \`${candidate.priority}\`
- **Runtime status:** ${candidate.priority === "high" ? "implemented in `SaveData.progressFacts`" : "research candidate only"}
- **What the player would see:** ${candidate.proposedDisplay}
- **Why it helps:** ${candidate.playerValue}
- **LLM context:** ${candidate.llmValue}
- **Safe interpretation rule:** ${candidate.interpretation}

Evidence:

${sources}
`;
}

async function main() {
  const [catalog, provenance] = await Promise.all([
    readJson(candidatesPath),
    readJson(provenancePath),
  ]);

  const verified = [];
  for (const candidate of catalog.candidates) {
    const evidence = [];
    for (const item of candidate.evidence) {
      evidence.push(await loadEvidence(candidate, item, provenance));
    }
    verified.push({ candidate, evidence });
  }

  const sections = [1, 2, 3].map((generation) => {
    const entries = verified
      .filter(({ candidate }) => candidate.generation === generation)
      .map(({ candidate, evidence }) => renderCandidate(candidate, evidence))
      .join("\n");
    return `## Generation ${generation}\n\n${entries}`;
  });

  const highPriority = verified.filter(({ candidate }) => candidate.priority === "high").length;
  const mediumPriority = verified.filter(({ candidate }) => candidate.priority === "medium").length;
  const generated = `# Progress Facts Prototype

This report is generated by \`scripts/generate-progress-fact-prototype.mjs\` from the pinned PRET checkouts recorded in \`provenance.json\`.

It is the source-audit report behind the runtime progress facts. High-priority entries are implemented in save/live readers and UI; medium-priority entries remain research candidates.

## Selection rule

Include a value only when it answers at least one of these questions:

1. What mandatory story step am I currently inside?
2. Which permanent choice did I make?
3. Is an important optional quest currently actionable or ready to collect?
4. Would the value materially improve the LLM's answer?

Exclude temporary script parameters, graphics variables, passive counters, and raw values with no verified player-facing interpretation.

Verified candidates: **${verified.length}** (${highPriority} high priority, ${mediumPriority} medium priority).

${sections.join("\n\n")}

## Implementation status

The high-priority candidates are exposed as derived progress facts while the existing flag model remains unchanged. Medium-priority facts are not runtime data and must not appear as main-story blockers without a separate implementation review.
`;

  await fs.writeFile(outputPath, generated);
  console.log(`Verified ${verified.length} progress fact candidates.`);
  console.log(`Wrote ${path.relative(root, outputPath)}.`);
}

await main();
