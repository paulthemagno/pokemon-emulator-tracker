import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const movesPath = path.join(root, "lib/pokemon/data/moves.ts");
const outputPath = path.join(root, "lib/pokemon/data/move-descriptions.ts");

const LOCAL_DESCRIPTIONS = {
  0: "No move in this slot.",
};

function normalizeText(text) {
  return String(text ?? "")
    .replace(/\f/g, " ")
    .replace(/\n/g, " ")
    .replace(/\s+/g, " ")
    .replace(/\$effect_chance/g, "")
    .trim();
}

function collectMoves(source) {
  const moves = [];
  const regex = /\{\s*id:\s*(\d+),\s*name:\s*"([^"]+)"/g;

  for (const match of source.matchAll(regex)) {
    const id = Number(match[1]);
    if (!Number.isFinite(id) || id <= 0) continue;
    moves.push({ id, name: match[2] });
  }

  return moves.sort((a, b) => a.id - b.id);
}

async function fetchPokeApiMove(id) {
  const response = await fetch(`https://pokeapi.co/api/v2/move/${id}`);
  if (!response.ok) return null;
  return response.json();
}

async function mapLimit(items, limit, worker) {
  const results = [];
  let nextIndex = 0;

  async function run() {
    while (nextIndex < items.length) {
      const index = nextIndex++;
      results[index] = await worker(items[index], index);
    }
  }

  await Promise.all(Array.from({ length: limit }, run));
  return results;
}

function toEntry(move, data) {
  const flavorTexts = {};
  for (const entry of data?.flavor_text_entries ?? []) {
    if (entry.language?.name !== "en" || !entry.version_group?.name) continue;
    const text = normalizeText(entry.flavor_text);
    if (text && !flavorTexts[entry.version_group.name]) {
      flavorTexts[entry.version_group.name] = text;
    }
  }

  const shortEffect = normalizeText(
    data?.effect_entries?.find((entry) => entry.language?.name === "en")?.short_effect
  );
  const firstFlavor = Object.values(flavorTexts)[0];
  const fallback = LOCAL_DESCRIPTIONS[move.id] || "No description available yet.";

  return {
    id: move.id,
    slug: data?.name || move.name.toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9-]/g, ""),
    name: move.name,
    flavorText: firstFlavor || shortEffect || fallback,
    flavorTexts,
    shortEffect: shortEffect || undefined,
    source: data ? "pokeapi" : "local",
  };
}

const source = await fs.readFile(movesPath, "utf8");
const moves = collectMoves(source);

const entries = await mapLimit(moves, 10, async (move, index) => {
  if ((index + 1) % 25 === 0) {
    console.log(`Fetched ${index + 1}/${moves.length}`);
  }

  let data = null;
  try {
    data = await fetchPokeApiMove(move.id);
  } catch {
    data = null;
  }

  return toEntry(move, data);
});

const serialized = JSON.stringify(
  Object.fromEntries(entries.map((entry) => [entry.id, entry])),
  null,
  2
);

const body = [
  "// Generated by scripts/generate-move-descriptions.mjs.",
  "// Source: PokeAPI move flavor/effect data for Gen 1-3 moves.",
  "",
  "export interface MoveDescriptionData {",
  "  id: number;",
  "  slug: string;",
  "  name: string;",
  "  flavorText: string;",
  "  flavorTexts: Record<string, string>;",
  "  shortEffect?: string;",
  "  source: \"pokeapi\" | \"local\";",
  "}",
  "",
  `export const MOVE_DESCRIPTIONS: Record<number, MoveDescriptionData> = ${serialized};`,
  "",
].join("\n");

await fs.writeFile(outputPath, body);
console.log(`Wrote ${entries.length} move descriptions to ${outputPath}`);
